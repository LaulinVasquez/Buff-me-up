import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const root = dirname(dirname(fileURLToPath(import.meta.url)));
// SQL Editor catch-up only. CLI users apply the original pending migrations instead.
const files = [
  "20261102000000_add_workout_substitutions.sql",
  "20261102020000_add_workout_set_logging.sql",
  "20261102030000_add_session_adaptations.sql",
];
const sources = files.map(file => {
  const source = readFileSync(join(root, "supabase/migrations", file), "utf8")
    .replace(/add column /g, "add column if not exists ")
    .replace(/create function /g, "create or replace function ")
    .replace(/create trigger (\w+) ([\s\S]*?) on (public\.\w+)\n/g,
      (_, name, timing, table) => `drop trigger if exists ${name} on ${table};\ncreate trigger ${name} ${timing} on ${table}\n`);
  return `-- SOURCE: ${file}\n${source.trim()}`;
}).join("\n\n");
const columns = [
  ["gym_workout_exercises", "substitution_version", "integer", true],
  ["gym_workout_exercises", "substitution_details", "jsonb", false],
  ["gym_workout_exercises", "substitution_history", "jsonb", true],
  ["gym_workout_exercises", "logged_sets", "jsonb", true],
  ["gym_workout_exercises", "log_revision", "integer", true],
  ["gym_workout_exercises", "deferred", "boolean", true],
  ["gym_workouts", "session_mode", "text", true],
  ["gym_workouts", "mode_minutes", "integer", false],
  ["gym_workouts", "mode_revision", "integer", true],
  ["gym_workouts", "session_adaptations", "jsonb", true],
];
const expected = columns.map(([table, column, type, required]) => `('${table}','${column}','${type}',${required})`).join(",\n  ");
const output = `-- Generated from workout migrations 7, 9 and 10. Do not edit this file directly.
-- SQL Editor recovery for an existing Buff Me Up database with migrations 1–6.
-- Preserves existing sessions/sets/history; missing fields receive their original defaults.
-- Does not record CLI migration history. See docs/SUPABASE_REPAIR_2026_11_06.md.
begin;
do $$
declare expected record; existing record;
begin
 if to_regprocedure('public.gym_set_workout_status(uuid,text)') is null
  or not exists(select 1 from pg_trigger where tgrelid=to_regclass('public.gym_workout_exercises') and tgname='gym_workout_exercises_guard_progress' and tgenabled='O')
  or not exists(select 1 from pg_class where oid=to_regclass('public.gym_workout_exercises') and relrowsecurity)
  or not exists(select 1 from pg_class where oid=to_regclass('public.gym_workouts') and relrowsecurity) then
  raise exception 'Workout recovery requires the original foundation and finalization migrations 1–6. Apply only missing prerequisites first.';
 end if;
 for expected in select * from (values
  ${expected}
 ) as columns(table_name,column_name,type_name,required) loop
  select format_type(a.atttypid,a.atttypmod) as type_name,a.attnotnull,d.adbin
   into existing from pg_attribute a
   left join pg_attrdef d on d.adrelid=a.attrelid and d.adnum=a.attnum
   where a.attrelid=to_regclass('public.'||expected.table_name)
    and a.attname=expected.column_name and not a.attisdropped;
  if found and (existing.type_name<>expected.type_name
    or existing.attnotnull<>expected.required
    or (expected.required and existing.adbin is null)) then
   raise exception 'Unexpected definition for %.%. Stop and inspect this partial schema before recovery.',expected.table_name,expected.column_name;
  end if;
 end loop;
end $$;

${sources}

notify pgrst, 'reload schema';
commit;
`;
const target = join(root, "supabase/deploy/workout_recovery_2026_11_06.sql");
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output) throw new Error("Workout recovery SQL is stale. Run npm run sql:workout-recovery.");
  console.log("PASS: workout recovery SQL matches migrations 7, 9 and 10");
} else {
  writeFileSync(target, output);
  console.log("Generated supabase/deploy/workout_recovery_2026_11_06.sql");
}
